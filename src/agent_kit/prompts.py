"""Versioned instructions, in the same layout as the GenAI Eval Framework's prompts as code (no dependency on it):

    prompts/<id>/<version>/prompt.yaml + system.md[.j2]
    prompts.lock: {prompts: {<id>: {stages: {prod: 1.0.0}, versions: {1.0.0: sha256:...}}}}
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml


@dataclass
class Instructions:
    id: str
    version: str
    hash: str
    text: str


def _hash(folder: Path) -> str:
    h = hashlib.sha256()
    for f in sorted(p for p in folder.rglob("*") if p.is_file()):
        h.update(f.relative_to(folder).as_posix().encode())
        h.update(f.read_bytes())
    return "sha256:" + h.hexdigest()


def resolve(prompts_dir: Path, spec: dict[str, Any], variables: dict[str, Any] | None = None) -> Instructions:
    if "text" in spec:
        t = str(spec["text"])
        return Instructions("inline", "0", "sha256:" + hashlib.sha256(t.encode()).hexdigest(), t)
    pid = spec["prompt"]
    ver = spec.get("version")
    lock_p = prompts_dir.parent / "prompts.lock"
    lock = (yaml.safe_load(lock_p.read_text(encoding="utf-8")) or {}).get("prompts", {}) if lock_p.exists() else {}
    if "@" in pid:
        pid, ver = pid.split("@", 1)
    if not ver:
        stage = spec.get("stage", "prod")
        ver = lock.get(pid, {}).get("stages", {}).get(stage)
        if not ver:
            raise FileNotFoundError(f"prompt {pid}: no version promoted to stage '{stage}' in {lock_p}")
    folder = prompts_dir / pid / str(ver)
    if not folder.is_dir():
        raise FileNotFoundError(f"prompt {pid}@{ver} not found in {prompts_dir}")
    h = _hash(folder)
    locked = lock.get(pid, {}).get("versions", {}).get(str(ver))
    if locked and locked != h:
        raise ValueError(f"prompt {pid}@{ver} was edited after it was locked; create a new version instead")
    f = next((folder / n for n in ("system.md.j2", "system.md") if (folder / n).exists()), None)
    if f is None:
        raise FileNotFoundError(f"prompt {pid}@{ver} has no system.md / system.md.j2")
    text = f.read_text(encoding="utf-8")
    if f.suffix == ".j2":
        from jinja2.sandbox import SandboxedEnvironment
        text = SandboxedEnvironment().from_string(text).render(**(variables or {}))
    return Instructions(pid, str(ver), h, text.strip())


def lock(prompts_dir: Path) -> dict[str, Any]:
    """Record hashes for every version folder (refuses if a locked version changed)."""
    lock_p = prompts_dir.parent / "prompts.lock"
    data = (yaml.safe_load(lock_p.read_text(encoding="utf-8")) or {}) if lock_p.exists() else {}
    prompts = data.setdefault("prompts", {})
    for pdir in sorted(d for d in prompts_dir.iterdir() if d.is_dir()):
        entry = prompts.setdefault(pdir.name, {"stages": {}, "versions": {}})
        for vdir in sorted(d for d in pdir.iterdir() if d.is_dir()):
            h = _hash(vdir)
            old = entry["versions"].get(vdir.name)
            if old and old != h:
                raise ValueError(f"{pdir.name}@{vdir.name} changed after it was locked; create a new version")
            entry["versions"][vdir.name] = h
    lock_p.write_text("# generated by `kit prompts lock`; promote with `kit prompts promote`\n" + yaml.safe_dump(data, sort_keys=True), encoding="utf-8")
    return data
